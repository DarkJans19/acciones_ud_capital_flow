from collections.abc import AsyncIterator, Sequence
from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol
from uuid import UUID

from acciones_ud.admin.domain.model import (
    AccountRestriction,
    BehaviorEvent,
    ComplianceReport,
    FeeVersion,
    KpiSnapshot,
    LedgerExecution,
    Raw,
    TradingHalt,
)
from acciones_ud.admin.domain.periods import Period
from acciones_ud.shared.domain.audit_entry import AuditRecord


class FeeRepository(Protocol):
    async def lock_scope(self, scope: str) -> None: ...
    async def all_versions(self) -> list[FeeVersion]: ...
    async def insert(self, value: FeeVersion) -> None: ...
    async def get_for_update(self, ident: UUID) -> FeeVersion | None: ...
    async def cancel(self, ident: UUID, at: datetime, actor: UUID, reason: str) -> bool: ...


class HaltRepository(Protocol):
    async def lock_scope(self, scope: str) -> None: ...
    async def all(self) -> list[TradingHalt]: ...
    async def insert(self, value: TradingHalt) -> None: ...
    async def get_for_update(self, ident: UUID) -> TradingHalt | None: ...
    async def release(self, ident: UUID, at: datetime, actor: UUID, reason: str) -> bool: ...


class RestrictionRepository(Protocol):
    async def lock_user(self, user: UUID) -> None: ...
    async def all(self, user_id: UUID | None = None) -> list[AccountRestriction]: ...
    async def insert(self, value: AccountRestriction) -> None: ...
    async def get_for_update(self, ident: UUID) -> AccountRestriction | None: ...
    async def lift(self, value: AccountRestriction) -> bool: ...


class AuditWriter(Protocol):
    async def append(self, record: AuditRecord) -> None: ...


class ReportRepository(Protocol):
    async def insert(self, value: ComplianceReport) -> None: ...
    async def get(self, ident: UUID) -> ComplianceReport | None: ...
    async def for_user(self, user: UUID) -> list[ComplianceReport]: ...


class SnapshotRepository(Protocol):
    async def get(self, period: Period, version: str) -> KpiSnapshot | None: ...
    async def upsert(self, value: KpiSnapshot) -> None: ...


class DispatchRepository(Protocol):
    async def lock(self, ident: UUID) -> None: ...
    async def get(self, ident: UUID) -> Raw | None: ...
    async def insert(self, record: Raw) -> None: ...
    async def source(self, ident: UUID) -> Raw | None: ...
    async def undispatched(self) -> list[UUID]: ...
    async def history(self, market: str, start: datetime, end: datetime) -> list[Raw]: ...


class AdminWork(Protocol):
    fees: FeeRepository
    halts: HaltRepository
    restrictions: RestrictionRepository
    audit: AuditWriter
    reports: ReportRepository
    snapshots: SnapshotRepository
    dispatches: DispatchRepository


class AdminWorkFactory(Protocol):
    def __call__(self) -> AbstractAsyncContextManager[AdminWork]: ...


class TotpVerifierPort(Protocol):
    async def has_active_totp(self, user_id: UUID) -> bool: ...
    async def verify(self, user_id: UUID, code: str, now: datetime) -> bool: ...


class MarketCatalogPort(Protocol):
    async def markets(self) -> list[Raw]: ...
    async def exchange_of(self, symbol: str) -> str | None: ...


class PlatformLedgerPort(Protocol):
    def iterate(
        self, start: datetime, end: datetime, filters: Raw | None = None
    ) -> AsyncIterator[LedgerExecution]: ...
    async def volume(self, start: datetime, end: datetime) -> list[Raw]: ...


class BrokerLinkPort(Protocol):
    async def linked_investors(self, broker_id: UUID) -> list[UUID]: ...
    async def is_linked(self, broker_id: UUID, investor_id: UUID) -> bool: ...


class UserReaderPort(Protocol):
    async def summary(self, user_id: UUID, at: datetime) -> Raw | None: ...
    async def display_names(self, ids: Sequence[UUID]) -> dict[UUID, str]: ...


class AuditTrailReader(Protocol):
    async def page(
        self, start: datetime, end: datetime, filters: Raw, cursor: str | None, size: int
    ) -> Raw: ...
    async def order_custody(self, order_id: UUID) -> Raw | None: ...
    async def counts(self, user: UUID, start: datetime, end: datetime) -> list[Raw]: ...
    async def behavior(self, start: datetime, end: datetime) -> list[BehaviorEvent]: ...


class KpiSourcePort(Protocol):
    async def inputs(self, period: Period, at: datetime) -> Raw: ...


class ScheduleChangePort(Protocol):
    async def apply(self, entry: Raw, now: datetime) -> int: ...


class ScheduleNotifierPort(Protocol):
    async def recipients(self) -> list[UUID]: ...
    async def notify(self, user_id: UUID, payload: Raw) -> None: ...
